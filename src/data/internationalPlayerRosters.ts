export function buildCompleteInitialPlayers(basePlayers: Player[]): Player[] {
  const existingNames = new Set(basePlayers.map(p => p.name.toLowerCase()));
  const extraPlayers: Player[] = [];

  // Add non-duplicate auction players
  for (const ap of AUCTION_PLAYERS_2026) {
    if (!existingNames.has(ap.name.toLowerCase())) {
      existingNames.add(ap.name.toLowerCase());
      extraPlayers.push(mapAuctionPlayerToPlayer(ap));
    }
  }

  // Add real international stars
  for (const ip of ADDITIONAL_REAL_INTL_PLAYERS) {
    if (!existingNames.has(ip.name.toLowerCase())) {
      existingNames.add(ip.name.toLowerCase());
      extraPlayers.push(ip);
    }
  }

  return [...basePlayers, ...extraPlayers];
}
