// Map an AUCTION_PLAYERS_2026 item to Player format
export function mapAuctionPlayerToPlayer(ap: typeof AUCTION_PLAYERS_2026[number]): Player {
  const primaryRole: Player['role'] =
    ap.pdfSpecialism === 'BATTER' ? 'Batter' :
    ap.pdfSpecialism === 'BOWLER' ? (ap.bowlingStyle?.toLowerCase().includes('spin') ? 'Spin' : 'Pace') :
    ap.pdfSpecialism === 'WICKETKEEPER' ? 'Wk-bat' : 'All-rounder';

  return {
    id: ap.id,
    name: ap.name,
    jerseyNumber: ap.jerseyNumber || (ap.listSrNo % 99) + 1,
    role: primaryRole,
    bowlingArm: ap.bowlingArm || (ap.bowlingStyle?.toLowerCase().includes('left') ? 'LAF' : 'RAF'),
    battingHand: ap.battingHand || 'RHB',
    age: ap.age || 26,
    country: ap.country,
    clubId: '',
    isOverseas: ap.isOverseas ?? (ap.country !== 'India'),
    tier: ap.tier || 'Gold',
    basePriceCr: ap.basePriceCr || 1.0,
    salaryCr: ap.basePriceCr || 1.0,
    ratings: {
      bat: ap.ratings?.bat || 75,
      pow: ap.ratings?.pow || 72,
      tec: ap.ratings?.tec || 74,
      tmp: ap.ratings?.tmp || 75,
      bowl: ap.ratings?.bowl || 45,
      ctrl: ap.ratings?.ctrl || 50,
      pace: ap.ratings?.pace || 50,
      dth: ap.ratings?.dth || 50,
      fit: ap.ratings?.fit || 82,
      comp: ap.ratings?.comp || 75,
      cat: ap.ratings?.cat || 72,
      fld: ap.ratings?.fld || 72
    },
    form: ap.form || 75,
    morale: ap.morale || 80,
    fitness: 95,
    isInjured: false,
    injuryDays: 0,
    stats: {
      matches: 0,
      runs: 0,
      balls: 0,
      fours: 0,
      sixes: 0,
      fifties: 0,
      hundreds: 0,
      highestScore: 0,
      wickets: 0,
      oversBowled: 0,
      runsConceded: 0,
      maidens: 0,
      bestBowling: '0/0'
    }
  };
}

